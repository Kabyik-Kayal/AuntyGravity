// Global install of the AuntyGravity hooks into Antigravity (~/.gemini/config/hooks.json).
// The hooks are started with --opt-in, so they do nothing in a project until `enable.mjs enable <dir>` is run for it.
// Usage: node poc/tools/install.mjs [install|uninstall|status] [--dry-run]
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const pocRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const hooksDir = path.join(pocRoot, 'workspace', '.agents', 'hooks');
export const KEY = 'auntygravity-global';

export const configDir = () => process.env.AUNTY_GEMINI_CONFIG_DIR || path.join(os.homedir(), '.gemini', 'config');
export const hooksFile = () => path.join(configDir(), 'hooks.json');

// Antigravity may run the command through `cmd /c` with its own argument escaping, which mangles quoted paths that
// contain spaces (this checkout lives under "Git-Hub Projects"). So the commands point at tiny shims in a space-free
// location that import the real hook scripts. If the shim path itself has spaces, fall back to quoting.
export const binDir = () => process.env.AUNTY_BIN_DIR || path.join(os.homedir(), '.auntygravity', 'bin');
const HOOKS = ['gate.mjs', 'record.mjs', 'inject-plan.mjs', 'stop-check.mjs'];
const shimPath = (f) => path.join(binDir(), f);

function writeShims() {
  fs.mkdirSync(binDir(), { recursive: true });
  for (const f of HOOKS) {
    fs.writeFileSync(shimPath(f), `// AuntyGravity hook shim (generated by tools/install.mjs). Do not edit.
await import(${JSON.stringify(pathToFileURL(path.join(hooksDir, f)).href)});
`);
  }
}

export function buildEntry() {
  const cmd = (f) => {
    const p = shimPath(f);
    return /[\s"]/.test(p) ? `node "${p}" --opt-in` : `node ${p} --opt-in`;
  };
  const handler = (f) => ({ type: 'command', command: cmd(f), timeout: 10 });
  return {
    PreToolUse: [{ matcher: '*', hooks: [handler('gate.mjs')] }],
    PostToolUse: [{ matcher: 'call_mcp_tool|.*consult.*', hooks: [handler('record.mjs')] }],
    PreInvocation: [handler('inject-plan.mjs')],
    Stop: [handler('stop-check.mjs')],
  };
}

const read = () => {
  try {
    return JSON.parse(fs.readFileSync(hooksFile(), 'utf8'));
  } catch (e) {
    if (e.code === 'ENOENT') return null;
    throw new Error(`${hooksFile()} exists but is not valid JSON (${e.message}); not touching it`);
  }
};

function write(obj) {
  const file = hooksFile();
  fs.mkdirSync(path.dirname(file), { recursive: true });
  if (fs.existsSync(file) && !fs.existsSync(`${file}.aunty.backup`)) fs.copyFileSync(file, `${file}.aunty.backup`);
  fs.writeFileSync(file, `${JSON.stringify(obj, null, 2)}\n`);
}

export function install({ dryRun = false } = {}) {
  const existing = read() ?? {};
  const next = { ...existing, [KEY]: buildEntry() };
  if (!dryRun) {
    writeShims();
    write(next);
  }
  return { file: hooksFile(), wrote: !dryRun, hooks: next[KEY], otherKeys: Object.keys(existing).filter((k) => k !== KEY) };
}

export function uninstall({ dryRun = false } = {}) {
  const existing = read();
  if (!existing || !(KEY in existing)) return { file: hooksFile(), removed: false };
  const { [KEY]: _gone, ...rest } = existing;
  if (!dryRun) {
    if (Object.keys(rest).length) write(rest);
    else fs.rmSync(hooksFile(), { force: true });
    for (const f of HOOKS) fs.rmSync(shimPath(f), { force: true });
  }
  return { file: hooksFile(), removed: !dryRun };
}

export const status = () => {
  const existing = read();
  return { file: hooksFile(), installed: Boolean(existing && KEY in existing), otherKeys: Object.keys(existing ?? {}).filter((k) => k !== KEY) };
};

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const [cmd = 'status', ...flags] = process.argv.slice(2);
  const dryRun = flags.includes('--dry-run');
  try {
    const r = cmd === 'install' ? install({ dryRun }) : cmd === 'uninstall' ? uninstall({ dryRun }) : status();
    console.log(JSON.stringify(r, null, 2));
    if (dryRun) console.log('(dry run: nothing was written)');
  } catch (e) {
    console.error(e.message);
    process.exitCode = 1;
  }
}
